def load(name: str):
    p = METRICS / name
    return json.loads(p.read_text(encoding="utf-8")) if p.is_file() else None


def table(rows: list[list], header: list[str]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


